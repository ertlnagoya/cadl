"""The module `version.py` of the Python target (Appendix K, K.11).

For a file that declares ``amendment: 0.1`` with an ``amendment:`` block,
`cadl codegen -t python` writes the identity of the version, the version
it replaces, its effective time, its transitional rules, and the values of
its amendable parameters, for the host that decides which version is in
force. The contract checks of the generated package keep no contract
instance from one step to the next: the host applies a version by running,
at each step, the package of the version in force (and, for an instance
that keeps an older version, the package of that version). The norms
monitor applies the transitional rules itself (K.11).
"""

from __future__ import annotations

from ..ast_nodes import SoSDefinition


def has_version_module(sos: SoSDefinition) -> bool:
    from ..amendment import amendment_declared
    raw = getattr(sos, "amendment", None)
    return amendment_declared(sos) and raw is not None and raw.has_block


def generate_version_module(sos: SoSDefinition) -> str:
    from ..amendment import analyse
    a = analyse(sos)
    params = {}
    units = {}
    for p in a.parameters:
        if p.value is None:
            continue
        if p.value.kind == "duration":
            params[p.id] = _num(p.value.value / 1000)
            units[p.id] = "s"
        else:
            params[p.id] = _num(p.value.value)
            units[p.id] = p.unit
    schedules = {m["id"]: [(dict(e["from"]), e["target"]) for e in m["schedule"]]
                 for m in a.metrics if m.get("schedule")}
    targets = {m.id: m.target for m in sos.metrics}
    transitional = {
        "default": a.transitional_default,
        "contracts": {c: {"rule": r, "in_states": list(st)}
                      for c, (r, st) in sorted(a.transitional.items())},
    }
    lines = [
        f'"""The version of the model {sos.name} (Appendix K, amendment 0.1).',
        "",
        "Generated by `cadl codegen -t python`. Do not edit. A host that runs",
        "several versions runs, at each step, the package of the version in",
        "force (Appendix K, K.11); `effective_time` places the effective time",
        'on the time stamps of the run."""',
        "",
        "from __future__ import annotations",
        "",
        "import datetime as _dt",
        "from fractions import Fraction",
        "",
        f"VERSION = {a.version!r}",
        f"PREVIOUS = {a.previous!r}",
        f"EFFECTIVE = {a.effective!r}",
        f"TRANSITIONAL = {transitional!r}",
        "# The values of the amendable parameters in this version: durations in",
        "# seconds. A regime binding (Appendix A, A.7.1) may give the same place",
        "# another value while the regime is current.",
        f"PARAMETERS = {params!r}",
        f"PARAMETER_UNITS = {units!r}",
        "# The schedules of the metrics (schedule:, K.5): metric -> [(from, target)].",
        f"SCHEDULES = {schedules!r}",
        "# The targets of the metrics (target:): metric -> target. With SCHEDULES, what",
        "# the target checks of metrics.py read of each version of a run (K.11).",
        f"TARGETS = {targets!r}",
        "",
        "",
        "def transitional_rule(contract_id: str) -> tuple:",
        '    """(rule, in_states or None) of a contract when this version takes',
        '    effect: "keep" or "switch" (Appendix K, K.4)."""',
        "    entry = TRANSITIONAL['contracts'].get(contract_id)",
        "    if entry is None:",
        "        return TRANSITIONAL['default'], None",
        "    return entry['rule'], (list(entry['in_states']) or None)",
        "",
        "",
        "def effective_time(period=None, origin=0, epoch: bool = False):",
        '    """The time stamp at which this version takes effect, as a Fraction:',
        "    for effective: { period: k }, origin + (k - 1) * period; for",
        "    effective: { at: ... }, seconds since 1970-01-01T00:00:00Z when",
        "    `epoch` is true. None when the version gives no effective time or",
        '    the time base has nothing for its form (K.11)."""',
        "    if not EFFECTIVE:",
        "        return None",
        "    (form, value), = EFFECTIVE.items()",
        "    if form == 'period':",
        "        if period is None:",
        "            return None",
        "        return Fraction(origin) + (int(value) - 1) * Fraction(period)",
        "    if not epoch:",
        "        return None",
        "    if value[-1:] in ('Z', 'z'):",
        "        value = value[:-1] + '+00:00'",
        "    try:",
        "        t = _dt.datetime.fromisoformat(value)",
        "    except ValueError:",
        "        t = _dt.datetime.combine(_dt.date.fromisoformat(value), _dt.time())",
        "    if t.tzinfo is None:",
        "        t = t.replace(tzinfo=_dt.timezone.utc)",
        "    d = t - _dt.datetime(1970, 1, 1, tzinfo=_dt.timezone.utc)",
        "    return Fraction(d.days * 86400 + d.seconds) + Fraction(d.microseconds, 1000000)",
        "",
    ]
    return "\n".join(lines)


def _num(v):
    return int(v) if v.denominator == 1 else float(v)
