"""Code target ``agent-rego``: the boundary policy of a file as one Rego
package (Appendix G, G.10).

The package takes the policy input of G.10 as ``input`` and returns the
result object of G.10 as ``result`` (and its ``decision``), for static
and non-static norms alike: a static norm is taken as in force, and the
in-force flags of the other norms and the valid derived instances are
read from ``input.instances``. It implements the same function as
:func:`cadl.agents.decide`. It is independent of the ``opa`` target.
"""

from __future__ import annotations

import json
from pathlib import Path

from ...agents import build_policy
from ...ast_nodes import SoSDefinition

PACKAGE = "cadl.agent_policy"
FILENAME = "agent_policy.rego"


def generate_agent_rego(sos: SoSDefinition, output_dir: Path) -> None:
    """Write ``agent_policy.rego`` for the enforced contracts of *sos*."""
    output_dir.mkdir(parents=True, exist_ok=True)
    (output_dir / FILENAME).write_text(generate_agent_rego_text(sos), encoding="utf-8")


def _comment(text: str) -> str:
    return " ".join(str(text).split())


def generate_agent_rego_text(sos: SoSDefinition) -> str:
    policy = build_policy(sos)
    lines: list[str] = []
    add = lines.append

    add(f"# Boundary policy generated by `cadl codegen -t agent-rego` from the SoS")
    add(f"# {_comment(policy['sos'])} (CADL agent governance extension, agents 0.1,")
    add("# Appendix G of the specification).")
    add("#")
    add("# input:  the policy input of G.10 (message; optional now; optional instances")
    add("#         with bindings, in_force and derived).")
    add(f"# output: data.{PACKAGE}.result, the result object of G.10 (decision, reason,")
    add("#         contracts, norms, provenance, escalate_to, timeout, fallback, notify),")
    add(f"#         and data.{PACKAGE}.decision (allow, deny or escalate).")
    add("#")
    add("# `result` is undefined for an input that is not a policy input (no message,")
    add("# an actor that is not written as NAME or NAME[3], instances that is not a")
    add("# list of objects); `decision` is then deny.")
    add("#")
    add("# The policy is stateless. Holds, release and expiry (G.6), the bookkeeping of")
    add("# grants, chains and revocations (G.7) and audit records (G.8) belong to the")
    add("# runtime. The policy is generated for one version of the contracts; an")
    add("# amendment requires a new policy.")
    add("#")
    add("# Enforced contracts and their norms:")
    if not policy["contracts"]:
        add("#   (none: every message is ungoverned)")
    for c in policy["contracts"]:
        default = c["default_decision"] or "omitted (deny tool calls, allow other messages)"
        add(f"#   {c['id']}: default {default}, point {c['point']}")
        for n in c["norms"]:
            kind = "static" if n["static"] else "NOT static"
            add(f"#     {n['id']}: {n['kind']}, {kind}: {_comment(n['content'])}")
    add("#")
    add("# Norms that are not static (G.10). The runtime supplies their in-force flag")
    add("# in input.instances[_].in_force; a missing flag is unknown, and unknown is")
    add("# resolved fail-closed (a prohibition applies, a permission does not):")
    non_static = [f"{c['id']}.{nid}" for c in policy["contracts"] for nid in c["non_static"]]
    for name in non_static:
        add(f"#   {name}")
    if not non_static:
        add("#   (none)")
    no_effect = [f"{c['id']}.{nid}" for c in policy["contracts"] for nid in c["no_effect"]]
    if no_effect:
        add("#")
        add("# Permissions and prohibitions whose content is not a message event have no")
        add("# effect at the boundary (G.5) and are not part of this policy:")
        for name in no_effect:
            add(f"#   {name}")
    add("")
    add(f"package {PACKAGE}")
    add("")
    add("import rego.v1")
    add("")
    add("# The actors and the enforced contracts of the file, as data (JSON).")
    text = json.dumps(policy, indent=2, ensure_ascii=False)
    if "`" in text:
        # A raw string cannot hold a backquote; write an escaped string.
        add("policy := json.unmarshal(" + json.dumps(text, ensure_ascii=False) + ")")
    else:
        add("policy := json.unmarshal(`" + text + "`)")
    add("")
    add(_LIBRARY_HEAD.strip("\n"))
    add("")
    add("# --- Norms -------------------------------------------------------------------")
    add("# One rule per permission and prohibition that takes part in decisions.")
    add("# 2 is true, 1 unknown, 0 false. A prohibition applies when the value is at")
    add("# least 1 (fail-closed), a permission only when it is 2.")
    add("")
    add("# Elements: [contract id, norm id, index of the instance in instances_of].")
    add("prohibition_applies contains [\"\", \"\", -1] if false")
    add("")
    add("# Elements: [contract id, norm id].")
    add("permission_applies contains [\"\", \"\"] if false")
    for c in policy["contracts"]:
        for n in c["norms"]:
            add("")
            lines.extend(_norm_rule(c, n))
    add("")
    add(_LIBRARY_TAIL.strip("\n"))
    add("")
    return "\n".join(lines)


def _norm_rule(c: dict, n: dict) -> list[str]:
    cid, nid = json.dumps(c["id"]), json.dumps(n["id"])
    static = "static" if n["static"] else "not static"
    out = [f"# {c['id']}.{n['id']}: {n['kind']}, {static}",
           f"#   {_comment(n['content'])}"]
    if n["static"]:
        value = "match_value(n, inst.bindings)"
        note = "\t# static: in force in every running instance"
    else:
        value = f"min([match_value(n, inst.bindings), in_force_value(inst, {nid})])"
        note = "\t# not static: the flag comes from input.instances[_].in_force"
    if n["kind"] == "prohibition":
        out += [
            f"prohibition_applies contains [{cid}, {nid}, k] if {{",
            f"\tinput.message.name == {json.dumps(n['name'])}",
            f"\tsome k, inst in instances_of({cid})",
            f"\tn := norm({cid}, {nid})",
            note,
            f"\t{value} >= 1",
            "}",
        ]
    else:
        out += [
            f"permission_applies contains [{cid}, {nid}] if {{",
            f"\tinput.message.name == {json.dumps(n['name'])}",
            f"\tsome inst in instances_of({cid})",
            f"\tn := norm({cid}, {nid})",
            note,
            f"\t{value} == 2",
            "}",
        ]
    return out


_LIBRARY_HEAD = r'''
# --- Result --------------------------------------------------------------------

default decision := "deny"

decision := result.decision

# Step 1 of G.5: no enforced contract governs the message.
result := plain_result("allow", "ungoverned") if {
	valid_input
	count(governing) == 0
}

# Step 2: a call of an undeclared tool.
result := plain_result("deny", "undeclared_tool") if {
	valid_input
	count(governing) > 0
	undeclared_tool
}

# Steps 3 and 4: the governing contracts decide; deny overrides.
result := {
	"decision": final,
	"reason": governed_reason,
	"contracts": [c.id | some c in policy.contracts; c.id in determining],
	"norms": [sprintf("%s.%s", [p[0], p[1].id]) | some p in array.concat(ground_pairs, permission_pairs)],
	"provenance": result_provenance,
	"escalate_to": result_escalate_to,
	"timeout": result_timeout,
	"fallback": result_fallback,
	"notify": result_notify,
} if {
	valid_input
	count(governing) > 0
	not undeclared_tool
	count(outcome) == count(governing)
}

plain_result(d, r) := {
	"decision": d,
	"reason": r,
	"contracts": [],
	"norms": [],
	"provenance": [],
	"escalate_to": null,
	"timeout": null,
	"fallback": [],
	"notify": [],
}

# --- Input ---------------------------------------------------------------------

valid_input if {
	is_string(input.message.name)
	input.message.name != ""
	is_object(sender)
	is_object(receiver)
	instances_ok
}

instances_ok if object.get(input, "instances", null) == null

instances_ok if {
	is_array(input.instances)
	every e in input.instances {
		is_object(e)
	}
}

sender := parse_actor(input.message.from)

receiver := parse_actor(input.message.to)

# A concrete actor: NAME, or NAME[3] for a member of a set.
parse_actor(s) := {"name": s, "index": null} if regex.match(`^[A-Za-z_][A-Za-z0-9_]*$`, s)

parse_actor(s) := {"name": m[1], "index": to_number(m[2])} if {
	some m in regex.find_all_string_submatch_n(`^([A-Za-z_][A-Za-z0-9_]*)\[(0|[1-9][0-9]*)\]$`, s, 1)
}

# The running instances of a contract. Without input.instances: one running
# instance, no index bound, no derived instance (G.10).
instances_of(_) := [{"bindings": {}, "in_force": {}, "derived": []}] if {
	object.get(input, "instances", null) == null
}

instances_of(cid) := [inst |
	some e in input.instances
	e.contract == cid
	inst := {
		"bindings": object.get(e, "bindings", {}),
		"in_force": object.get(e, "in_force", {}),
		"derived": object.get(e, "derived", []),
	}
] if {
	is_array(input.instances)
}

# --- Matching (G.4): 2 is true, 1 unknown, 0 false ---------------------------------

# Whether a concrete actor is the declared actor `name` or a member of the set.
is_member(name, a) if {
	a.name == name
	d := policy.actors[name]
	not d.indexed
	a.index == null
}

is_member(name, a) if {
	a.name == name
	d := policy.actors[name]
	d.indexed
	a.index != null
	in_bounds(d, a.index)
}

in_bounds(d, _) if not d.bounded

in_bounds(d, i) if {
	d.bounded
	i >= d.lo
	i <= d.hi
}

ref_true(ref, a, _) if {
	ref.kind == "plain"
	is_member(ref.name, a)
	a.index == null
}

ref_true(ref, a, _) if {
	ref.kind == "index"
	is_member(ref.name, a)
	a.index == ref.index
}

ref_true(ref, a, _) if {
	ref.kind == "all"
	is_member(ref.name, a)
	a.index != null
}

ref_true(ref, a, _) if {
	ref.kind == "range"
	is_member(ref.name, a)
	a.index != null
	a.index >= ref.lo
	a.index <= ref.hi
}

# A[i]: exactly A[v] when the contract instance binds i to v ...
ref_true(ref, a, bindings) if {
	ref.kind == "var"
	is_member(ref.name, a)
	a.index != null
	is_number(bindings[ref.var])
	a.index == bindings[ref.var]
}

# ... and unknown when it binds no value to i.
ref_unknown(ref, a, bindings) if {
	ref.kind == "var"
	is_member(ref.name, a)
	a.index != null
	not is_number(bindings[ref.var])
}

ref_match(ref, a, bindings) := 2 if ref_true(ref, a, bindings)

ref_match(ref, a, bindings) := 1 if {
	not ref_true(ref, a, bindings)
	ref_unknown(ref, a, bindings)
}

ref_match(ref, a, bindings) := 0 if {
	not ref_true(ref, a, bindings)
	not ref_unknown(ref, a, bindings)
}

# The in-force flag of a norm that is not static; a missing entry is unknown.
in_force_value(inst, id) := 2 if inst.in_force[id] == true

in_force_value(inst, id) := 0 if inst.in_force[id] == false

in_force_value(inst, id) := 1 if {
	not inst.in_force[id] == true
	not inst.in_force[id] == false
}

norm_in_force(n, _) := 2 if n.static

norm_in_force(n, inst) := in_force_value(inst, n.id) if not n.static

norm(cid, nid) := n if {
	some c in policy.contracts
	c.id == cid
	some n in c.norms
	n.id == nid
}

# The content matches the message (the name is tested by the rule of the norm)
# and the sender of the message is the bearer: Kleene conjunction.
match_value(n, bindings) := min([
	ref_match(n.sender, sender, bindings),
	ref_match(n.receiver, receiver, bindings),
	ref_match(n.bearer, sender, bindings),
])

# --- Messages (G.4) and governed messages (G.5) -------------------------------------

tool_server if {
	is_member(receiver.name, receiver)
	policy.actors[receiver.name].kind == "tool_server"
}

tool_call if {
	tool_server
	input.message.name in policy.actors[receiver.name].tools
}

undeclared_tool if {
	tool_server
	not tool_call
}

# An unknown match with a party counts.
party_match(c, a) if {
	some ref in c.parties
	ref_match(ref, a, {}) >= 1
}

governing contains c.id if {
	some c in policy.contracts
	party_match(c, sender)
	party_match(c, receiver)
}

# A message to a tool server that is a party is governed whatever its sender.
governing contains c.id if {
	some c in policy.contracts
	tool_server
	party_match(c, receiver)
}
'''

_LIBRARY_TAIL = r'''
# --- Derived instances (G.7) ----------------------------------------------------
# The runtime lists in input.instances[_].derived the derived instances it found
# valid. What can be read from the contract is tested again; an entry that fails
# a test does not apply. Elements: [contract id, norm id, chain].

derived_applies contains [c.id, n.id, d.chain] if {
	some c in policy.contracts
	some inst in instances_of(c.id)
	some d in inst.derived
	some n in c.norms
	n.kind == "permission"
	n.id == d.norm
	deleg := c.delegations[n.id]
	d.holder == input.message.from
	n.name == input.message.name
	ref_match(n.receiver, receiver, inst.bindings) == 2
	norm_in_force(n, inst) == 2
	is_array(d.chain)
	count(d.chain) >= 2
	d.chain[count(d.chain) - 1] == d.holder
	count(d.chain) - 1 <= deleg.max_depth
	ref_match(n.bearer, parse_actor(d.chain[0]), inst.bindings) == 2
	every a in array.slice(d.chain, 1, count(d.chain)) {
		link_ok(deleg, a)
	}
}

link_ok(deleg, a) if {
	some ref in deleg.to
	ref_match(ref, parse_actor(a), {}) == 2
}

# --- Step 3 of G.5: each governing contract decides ------------------------------

grounds(cid) := {x[1] | some x in prohibition_applies; x[0] == cid}

permissions(cid) := {x[1] | some x in permission_applies; x[0] == cid} | {x[1] | some x in derived_applies; x[0] == cid}

# The concrete actor named by escalate_to:, or null when the prohibition has
# none or its index is not bound.
approver(n, _) := null if n.escalate == null

approver(n, _) := n.escalate.name if n.escalate.kind == "plain"

approver(n, _) := sprintf("%s[%d]", [n.escalate.name, n.escalate.index]) if n.escalate.kind == "index"

approver(n, inst) := sprintf("%s[%d]", [n.escalate.name, inst.bindings[n.escalate.var]]) if {
	n.escalate.kind == "var"
	is_number(inst.bindings[n.escalate.var])
}

approver(n, inst) := null if {
	n.escalate.kind == "var"
	not is_number(inst.bindings[n.escalate.var])
}

approver(n, _) := null if n.escalate.kind in {"all", "range"}

contract_approvers(c) := {a |
	some x in prohibition_applies
	x[0] == c.id
	n := norm(c.id, x[1])
	a := approver(n, instances_of(c.id)[x[2]])
}

# Every ground has an escalate_to, all name the same actor, and that actor is
# not the sender of the message.
can_escalate(c) if {
	approvers := contract_approvers(c)
	count(approvers) == 1
	some a in approvers
	a != null
	a != input.message.from
}

no_instance(c) if count(instances_of(c.id)) == 0

has_grounds(c) if count(grounds(c.id)) > 0

has_permission(c) if count(permissions(c.id)) > 0

# Step 3.4: default: or, when omitted, deny for a tool call and allow for every
# other message.
default_for(c) := c.default_decision if c.default_decision != null

default_for(c) := "deny" if {
	c.default_decision == null
	tool_call
}

default_for(c) := "allow" if {
	c.default_decision == null
	not tool_call
}

contract_outcome(c) := {"decision": "deny", "reason": "no_instance"} if {
	no_instance(c)
	tool_call
}

contract_outcome(c) := {"decision": default_for(c), "reason": "default"} if {
	no_instance(c)
	not tool_call
}

contract_outcome(c) := {"decision": "escalate", "reason": "prohibition"} if {
	not no_instance(c)
	has_grounds(c)
	can_escalate(c)
}

contract_outcome(c) := {"decision": "deny", "reason": "prohibition"} if {
	not no_instance(c)
	has_grounds(c)
	not can_escalate(c)
}

contract_outcome(c) := {"decision": "allow", "reason": "permission"} if {
	not no_instance(c)
	not has_grounds(c)
	has_permission(c)
}

contract_outcome(c) := {"decision": default_for(c), "reason": "default"} if {
	not no_instance(c)
	not has_grounds(c)
	not has_permission(c)
}

outcome[cid] := o if {
	some c in policy.contracts
	cid := c.id
	cid in governing
	o := contract_outcome(c)
}

# --- Step 4 of G.5: combination, deny overrides -----------------------------------

deny_ids := {cid | some cid, o in outcome; o.decision == "deny"}

escalate_ids := {cid | some cid, o in outcome; o.decision == "escalate"}

all_approvers := {a |
	some c in policy.contracts
	c.id in escalate_ids
	some a in contract_approvers(c)
}

final := "deny" if count(deny_ids) > 0

final := "escalate" if {
	count(deny_ids) == 0
	count(escalate_ids) > 0
	count(all_approvers) == 1
}

# A hold has a single approver.
final := "deny" if {
	count(deny_ids) == 0
	count(escalate_ids) > 0
	count(all_approvers) != 1
}

final := "allow" if {
	count(deny_ids) == 0
	count(escalate_ids) == 0
}

determining := deny_ids if count(deny_ids) > 0

determining := escalate_ids if {
	count(deny_ids) == 0
	count(escalate_ids) > 0
}

determining := governing if {
	count(deny_ids) == 0
	count(escalate_ids) == 0
}

determining_reasons := {outcome[cid].reason | some cid in determining}

governed_reason := "permission" if {
	final == "allow"
	"permission" in determining_reasons
}

governed_reason := "default" if {
	final == "allow"
	not "permission" in determining_reasons
}

governed_reason := "no_instance" if {
	final != "allow"
	"no_instance" in determining_reasons
}

governed_reason := "prohibition" if {
	final != "allow"
	not "no_instance" in determining_reasons
	"prohibition" in determining_reasons
}

governed_reason := "default" if {
	final != "allow"
	not "no_instance" in determining_reasons
	not "prohibition" in determining_reasons
}

# The grounds, or the applying permissions, of the determining contracts, in
# the order of declaration. Elements: [contract id, norm].
ground_pairs := [[c.id, n] |
	governed_reason == "prohibition"
	some c in policy.contracts
	c.id in determining
	some n in c.norms
	n.kind == "prohibition"
	n.id in grounds(c.id)
]

permission_pairs := [[c.id, n] |
	governed_reason == "permission"
	some c in policy.contracts
	c.id in determining
	some n in c.norms
	n.kind == "permission"
	n.id in permissions(c.id)
]

provenance_all := [d.chain |
	some p in permission_pairs
	some inst in instances_of(p[0])
	some d in inst.derived
	d.norm == p[1].id
	[p[0], p[1].id, d.chain] in derived_applies
]

result_provenance := [x | some i, x in provenance_all; not x in array.slice(provenance_all, 0, i)]

result_escalate_to := a if {
	final == "escalate"
	some a in all_approvers
}

result_escalate_to := null if final != "escalate"

timeouts := [p[1].timeout_ms | some p in ground_pairs; p[1].timeout_ms != null]

result_timeout := min(timeouts) if count(timeouts) > 0

result_timeout := null if count(timeouts) == 0

fallback_all := [p[1].fallback | some p in ground_pairs; p[1].fallback != null]

result_fallback := [x | some i, x in fallback_all; not x in array.slice(fallback_all, 0, i)]

notify_all := [p[1].notify | some p in ground_pairs; p[1].notify != null]

result_notify := [x | some i, x in notify_all; not x in array.slice(notify_all, 0, i)]
'''
